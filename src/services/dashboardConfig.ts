export function getAvailableWidgetsForUser(user: User): WidgetDefinition[] {
  return ALL_WIDGETS.filter((w) => {
    // Role check
    if (!w.roles.includes(user.role)) return false;

    // Permission check if admin
    if (w.requiredPermission && user.adminPermissions) {
      const permValue = user.adminPermissions[w.requiredPermission];
      if (!permValue) return false;
    }

    return true;
  });
}

export function getDefaultDashboardConfig(user: User): UserDashboardConfig {
  const available = getAvailableWidgetsForUser(user);
  const defaultVisibleIds = available.filter((w) => w.defaultVisible).map((w) => w.id);

  return {
    visibleWidgets: defaultVisibleIds,
    widgetOrder: available.map((w) => w.id),
    collapsedWidgets: {},
    focusMode: false,
    hasCompletedFocusOnboarding: false,
    dismissedTips: {},
  };
}

